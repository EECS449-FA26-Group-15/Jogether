"""Build geo_data.jac from tools/landmark_seed.py.

Looks up coordinates for new landmarks (OSM Nominatim), walking distances between
every pair of landmarks (OSRM foot router, one table call), and elevation
(Open-Meteo). Writes the result as Jac dict literals so the app and its tests
never need the network.

Run from the repository root:  python3 tools/build_geo.py
"""
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from landmark_seed import KNOWN_COORDS, LANDMARKS  # noqa: E402

UA = "Jogether-course-project/0.2 (EECS 449, University of Michigan)"
OUT = Path(__file__).parent.parent / "geo_data.jac"
CACHE = Path(__file__).parent / "geo_cache.json"


def get(url: str, data: bytes | None = None) -> dict | list:
    req = urllib.request.Request(url, data=data, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.load(resp)


def main() -> None:
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {"coords": {}, "elev": {}}
    coords: dict[str, tuple[float, float]] = dict(KNOWN_COORDS)
    coords.update({k: tuple(v) for k, v in cache["coords"].items()})

    # 1. Coordinates for landmarks we do not have yet (Nominatim, 1 request/s).
    for name, _area, _d, _l, _s, _t, _tags, query in LANDMARKS:
        if name in coords:
            continue
        q = query or f"{name}, Ann Arbor, Michigan"
        url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(
            {"q": q, "format": "json", "limit": 1, "countrycodes": "us"}
        )
        hits = get(url)
        time.sleep(1.1)
        if not hits:
            print(f"!! no Nominatim hit for {name!r} (query {q!r})", file=sys.stderr)
            continue
        lat, lon = round(float(hits[0]["lat"]), 5), round(float(hits[0]["lon"]), 5)
        coords[name] = (lat, lon)
        cache["coords"][name] = [lat, lon]
        print(f"{name}: {lat},{lon}  [{hits[0].get('display_name', '')[:70]}]")
    CACHE.write_text(json.dumps(cache, indent=1))

    names = [lm[0] for lm in LANDMARKS if lm[0] in coords]
    missing = [lm[0] for lm in LANDMARKS if lm[0] not in coords]
    if missing:
        print("Missing coordinates, left out:", missing, file=sys.stderr)

    # 2. Walking distances for every pair in one OSRM table call.
    locs = ";".join(f"{coords[n][1]},{coords[n][0]}" for n in names)
    table = get(
        f"https://routing.openstreetmap.de/routed-foot/table/v1/foot/{locs}?annotations=distance"
    )
    if table.get("code") != "Ok":
        raise SystemExit(f"OSRM table failed: {table}")
    dist = table["distances"]
    walk: dict[str, float] = {}
    for i, a in enumerate(names):
        for j, b in enumerate(names):
            if j <= i:
                continue
            d_ab, d_ba = dist[i][j], dist[j][i]
            vals = [v for v in (d_ab, d_ba) if v is not None]
            if not vals:
                print(f"!! OSRM has no route {a} <-> {b}", file=sys.stderr)
                continue
            walk[f"{a}|{b}"] = round(sum(vals) / len(vals) / 1000.0, 3)

    # 3. Elevation (Open-Meteo), cached.
    need = [n for n in names if n not in cache["elev"]]
    if need:
        url = "https://api.open-meteo.com/v1/elevation?" + urllib.parse.urlencode(
            {"latitude": ",".join(str(coords[n][0]) for n in need),
             "longitude": ",".join(str(coords[n][1]) for n in need)}
        )
        elev = get(url)["elevation"]
        for n, e in zip(need, elev):
            cache["elev"][n] = float(e)
        CACHE.write_text(json.dumps(cache, indent=1))
    elevation = {n: cache["elev"][n] for n in names}

    # 4. Write geo_data.jac
    def jdict(d: dict, fmt) -> str:
        lines = ",\n".join(f"         {json.dumps(k)}: {fmt(v)}" for k, v in d.items())
        return "{\n" + lines + "\n     }"

    body = f'''"""Generated by tools/build_geo.py on {time.strftime("%Y-%m-%d")}. Do not edit by hand.

Coordinates: OpenStreetMap Nominatim. Walking distances: OSRM foot router on
OpenStreetMap (routing.openstreetmap.de), km, averaged over both directions.
Elevation: Open-Meteo, metres above sea level.
"""

glob COORDS: dict[str, tuple[float, float]] = {jdict({n: coords[n] for n in names}, lambda v: f"({v[0]}, {v[1]})")};

glob WALK_KM: dict[str, float] = {jdict(walk, str)};

glob ELEVATION_M: dict[str, float] = {jdict(elevation, str)};
'''
    OUT.write_text(body)
    print(f"wrote {OUT}: {len(names)} landmarks, {len(walk)} pairs")

    # 5. Write landmarks.jac from the seed (names match geo_data.jac exactly).
    def lit(v): return json.dumps(v)
    entries = []
    for name, area, desc, light, surf, times, tags, _q in LANDMARKS:
        if name not in coords:
            continue
        tlist = "ALL_DAY" if times == ["morning", "afternoon", "evening"] else "DAYTIME"
        entries.append(
            "        Landmark(\n"
            f"            name={lit(name)},\n            area={lit(area)},\n"
            f"            description={lit(desc)},\n            lighting={lit(light)},\n"
            f"            surface={lit(surf)},\n            good_times={tlist},\n"
            f"            tags={lit(tags)}\n        )"
        )
    landmarks_jac = (
        '"""Curated landmarks the route agent may use. Generated by tools/build_geo.py from\n'
        'tools/landmark_seed.py; edit the seed, not this file.\n\n'
        'Draft list: lighting and surface are best guesses. Check them on the ground\n'
        'before the agent\'s safety notes rely on them.\n"""\n\n'
        'obj Landmark {\n'
        '    has name: str,\n        area: str,\n        description: str,\n        lighting: str,\n'
        '        surface: str,\n        good_times: list[str],\n        tags: list[str] = [];\n}\n\n'
        'glob ALL_DAY: list[str] = ["morning", "afternoon", "evening"];\n'
        'glob DAYTIME: list[str] = ["morning", "afternoon"];\n\n'
        '"""Tags a landmark can carry; the preference parser may only use these."""\n'
        'glob TAGS: list[str] = ["river", "park", "nature", "trail", "campus", "shops", "historic", '
        '"quiet", "busy", "stadium", "track", "hill", "flat"];\n\n'
        'glob AREAS: list[str] = ["central-campus", "north-campus", "downtown"];\n\n'
        '"""Every landmark in every area."""\n'
        'def all_landmarks -> list[Landmark] {\n    return [\n' + ",\n".join(entries) + '\n    ];\n}\n\n'
        '"""Landmarks whose home area is `area`; an unknown area has none."""\n'
        'def landmarks_for(area: str) -> list[Landmark] {\n'
        '    return [lm for lm in all_landmarks() if lm.area == area];\n}\n\n'
        '"""The landmark with this exact name, or None."""\n'
        'def landmark_named(name: str) -> Landmark | None {\n'
        '    for lm in all_landmarks() {\n        if lm.name == name {\n            return lm;\n        }\n    }\n'
        '    return None;\n}\n'
    )
    (Path(__file__).parent.parent / "landmarks.jac").write_text(landmarks_jac)
    print(f"wrote landmarks.jac: {len(entries)} landmarks")


if __name__ == "__main__":
    main()
